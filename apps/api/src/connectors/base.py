from typing import Protocol

from ..models import NormalizedIncomeDataset, Place, SourceCandidate


class IncomeConnector(Protocol):
    def supports(self, place: Place) -> tuple[float, str]: ...
    async def discover(self, place: Place, year: int) -> list[SourceCandidate]: ...
    async def fetch(self, candidate: SourceCandidate, place: Place) -> list[list[list[str]]]: ...
    def normalize(
        self, raw, candidate: SourceCandidate, place: Place
    ) -> NormalizedIncomeDataset: ...
    async def get_boundaries(self, year: int, layer_name: str = "Census Tracts") -> dict: ...
    async def get_extent(self, year: int) -> dict: ...
    def outline(self, extent: dict) -> dict: ...
    def validate_geography(
        self, dataset: NormalizedIncomeDataset, boundaries: dict, extent: dict
    ) -> tuple[dict, dict, list[str]]: ...
